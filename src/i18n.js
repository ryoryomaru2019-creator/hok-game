let currentLang = 'ja';
const langChangeListeners = [];

export function onLangChange(fn) {
  if (typeof fn === 'function') {
    langChangeListeners.push(fn);
  }
}

export function getLang() {
  return currentLang;
}

export const getCurrentLang = getLang;

export function setLang(lang) {
  if (translations[lang]) {
    currentLang = lang;
    localStorage.setItem('hirame_lang', lang);
    updateDOMText();
    langChangeListeners.forEach(fn => {
      try { fn(currentLang); } catch (e) { console.error(e); }
    });
  }
}

export function t(key) {
  return translations[currentLang]?.[key] || translations.ja[key] || key;
}


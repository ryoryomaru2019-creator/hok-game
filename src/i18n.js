export function initI18n() {
  const saved = localStorage.getItem('hirame_lang');
  const browserLang = navigator.language?.toLowerCase() || '';
  if (saved && translations[saved]) {
    currentLang = saved;
  } else if (browserLang.startsWith('en')) {
    currentLang = 'en';
  } else if (browserLang.startsWith('ko')) {
    currentLang = 'ko';
  } else if (browserLang.startsWith('zh')) {
    currentLang = 'zh';
  } else {
    currentLang = 'ja';
  }
  updateDOMText();
  langChangeListeners.forEach(fn => {
    try { fn(currentLang); } catch (e) { console.error(e); }
  });
}

export function updateDOMText() {
  // 言語選択ボタンのactive同期
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === currentLang);
  });

  // ドキュメントタイトルの動的更新
  if (translations[currentLang]?.title) {
    const titleStr = translations[currentLang].title.replace(/\n/g, ' ');
    document.title = `${titleStr} - ${translations[currentLang].subtitle}`;
  }

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key && translations[currentLang]?.[key]) {
      if (el.tagName === 'INPUT' && el.getAttribute('type') === 'text') {
        el.placeholder = translations[currentLang][key];
      } else {
        el.innerText = translations[currentLang][key];
      }
    }
  });

  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (key && translations[currentLang]?.[key]) {
      el.setAttribute('title', translations[currentLang][key]);
    }
  });
}
